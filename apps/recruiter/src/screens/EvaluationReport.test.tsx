describe("question and evidence drill-down", () => {
  it("shows what was asked, what came back, and what was taken from it", async () => {
    await renderReport({ result: result() });
    const fixture = resultFixture as unknown as AssessmentResult;
    const skill = fixture.skills.find(
      (s) => s.discussion_status === "discussed" && s.evidence_count > 0,
    )!;
    const card = cardFor(skill.skill_name);
    await userEvent.click(within(card).getByText(/Questions and evidence/));
    // Scoped to the drill-down: the skill header shows its own depth summary,
    // so the same wording legitimately appears twice on the card.
    const drilldown = within(card).getByText(/Questions and evidence/)
      .closest("details")! as HTMLElement;

    const question = fixture.questions.find((q) => q.skill_id === skill.skill_id)!;
    expect(within(drilldown).getByText(question.question_text)).toBeInTheDocument();
    for (const turn of question.turns) {
      if (turn.answer) {
        expect(within(drilldown).getByText(turn.answer)).toBeInTheDocument();
      }
    }
    const item = fixture.evidence.find((e) => e.skill_id === skill.skill_id)!;
    expect(within(drilldown).getByText(`“${item.candidate_quote}”`)).toBeInTheDocument();
    expect(
      within(drilldown).getByText(new RegExp(`Turn ${item.turn_id}`)),
    ).toBeInTheDocument();
    // More than one item can bear on the same criterion; that is the data,
    // not a duplicate render.
    expect(
      within(drilldown).getAllByText(new RegExp(`supports ${item.supports_criterion}`))
        .length,
    ).toBeGreaterThan(0);
  });

  it("shows each question's own depth pair", async () => {
    await renderReport({ result: result() });
    const fixture = resultFixture as unknown as AssessmentResult;
    const skill = fixture.skills.find((s) => s.skill_name === "Reconciliation")!;
    const card = cardFor(skill.skill_name);
    await userEvent.click(within(card).getByText(/Questions and evidence/));
    const drilldown = within(card).getByText(/Questions and evidence/)
      .closest("details")! as HTMLElement;
    // The question's own pair, not the skill header's.
    expect(
      within(drilldown).getByText(/Reached Direct · Demonstrated Deep probed/),
    ).toBeInTheDocument();
  });

  it("quotes the candidate verbatim, exactly as the API validated it", async () => {
    await renderReport({ result: result() });
    for (const item of (resultFixture as unknown as AssessmentResult).evidence) {
      expect(screen.getByText(`“${item.candidate_quote}”`)).toBeInTheDocument();
    }
  });

  it("invents nothing when a skill produced no evidence", async () => {
    await renderReport({
      result: result((r) => {
        r.evidence = [];
        r.skills.forEach((s) => {
          s.evidence_count = 0;
        });
      }),
    });
    expect(screen.queryAllByRole("blockquote" as never)).toHaveLength(0);
  });

  it("marks a turn the scanner excluded rather than hiding it", async () => {
    await renderReport({
      result: result((r) => {
        r.questions[0].turns[0].excluded = true;
        r.questions[0].turns[0].excluded_reason = "override attempt";
      }),
    });
    const skill = (resultFixture as unknown as AssessmentResult).skills.find(
      (s) => s.skill_id === (resultFixture as unknown as AssessmentResult).questions[0].skill_id,
    )!;
    const card = cardFor(skill.skill_name);
    await userEvent.click(within(card).getByText(/Questions and evidence/));
    expect(within(card).getByText(/Excluded · override attempt/)).toBeInTheDocument();
  });
});

