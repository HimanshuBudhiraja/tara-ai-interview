/**
 * The recruiter's evaluation report, against the canonical assessment result.
 *
 * Every fixture was generated by `tools/make_report_fixtures.py` from the real
 * serialisers — `result.json` comes out of `result.build_validated`, the same
 * function the endpoint calls — so these tests run against the contract the
 * backend actually sends. Regenerating them after a contract change is what
 * makes drift show up here instead of in front of a recruiter.
 *
 * The evaluation in them came from an injected extractor, not a model. What is
 * verified is the UI and its integration with the API.
 */

const SESSION = "8c61817c76f54a36bd3df1b4199a3f9c";
const RESULT_URL = `/api/recruiter/sessions/${SESSION}/evaluation/result`;

type Stub = {
  /** 200 — a completed, self-consistent assessment. */
  result?: unknown;
  /** 409 with a status envelope — pending, running or failed. */
  statusEnvelope?: unknown;
  /** 409 with violations — the result contradicted itself. */
  violations?: string[];
  /** 404, 403, 500 … */
  status?: number;
  detail?: string;
};

function stubApi(stub: Stub) {
  const calls: string[] = [];
  const fetchMock = vi.fn(async (url: string, _init?: RequestInit) => {
    calls.push(String(url));
    if (stub.result) {
      return {
        ok: true, status: 200, json: async () => stub.result,
      } as unknown as Response;
    }
    if (stub.statusEnvelope) {
      return {
        ok: false, status: 409,
        json: async () => ({
          detail: {
            message: `The evaluation is ${
              (stub.statusEnvelope as Evaluation).status
            }; there is no result yet.`,
            evaluation: stub.statusEnvelope,
          },
        }),
      } as unknown as Response;
    }
    if (stub.violations) {
      return {
        ok: false, status: 409,
        json: async () => ({
          detail: {
            message:
              "The assessment result does not agree with itself and has not been shown.",
            violations: stub.violations,
          },
        }),
      } as unknown as Response;
    }
    const status = stub.status ?? 404;
    return {
      ok: false, status,
      json: async () => ({ detail: stub.detail ?? "nope" }),
    } as unknown as Response;
  });
  vi.stubGlobal("fetch", fetchMock);
  return { calls, fetchMock };
}

function result(patch: (r: AssessmentResult) => void = () => undefined): AssessmentResult {
  const copy = structuredClone(resultFixture) as unknown as AssessmentResult;
  patch(copy);
  return copy;
}

async function renderReport(stub: Stub) {
  const api = stubApi(stub);
  render(<EvaluationReport sessionId={SESSION} />);
  await waitFor(() => expect(screen.queryByText(/loading the evaluation/i)).toBeNull());
  return api;
}

function cardFor(skill: string): HTMLElement {
  return screen.getByRole("heading", { name: skill }).closest("article")!;
}

