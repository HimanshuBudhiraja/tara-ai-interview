describe("loading", () => {
  it("renders the whole assessment from a single request", async () => {
    const { calls } = await renderReport({ result: result() });
    // Every figure on the page comes from one response, so the report can never
    // show halves of two different evaluations. The pilot-review panel fetches
    // its own list separately — that is a note about the assessment, not part
    // of it, and it is filtered out here rather than relaxing the rule.
    expect(calls.filter((url) => !url.endsWith("/review"))).toEqual([RESULT_URL]);
    expect(screen.getByText("Skill assessment")).toBeInTheDocument();
  });

  it("renders a completed assessment", async () => {
    await renderReport({ result: result() });
    expect(screen.getByRole("heading", { name: "Priya Sharma" })).toBeInTheDocument();
    expect(screen.getByText("Evaluated")).toBeInTheDocument();
  });

  it("renders a pending evaluation without any score", async () => {
    await renderReport({ statusEnvelope: pendingFixture });
    expect(screen.getAllByText(/evaluation queued/i).length).toBeGreaterThan(0);
    expect(screen.queryByText(/total score/i)).toBeNull();
    expect(screen.queryByText(/skill assessment/i)).toBeNull();
    expect(screen.queryByText(/interview coverage/i)).toBeNull();
  });

  it("renders a running evaluation without partial scoring", async () => {
    await renderReport({ statusEnvelope: runningFixture });
    expect(screen.getAllByText(/evaluation running/i).length).toBeGreaterThan(0);
    expect(screen.queryByText(/overall rating/i)).toBeNull();
  });

  it("renders a failure as a failed run, not as a poor candidate", async () => {
    await renderReport({ statusEnvelope: failedFixture });
    expect(screen.getByRole("heading", { name: /evaluation failed/i })).toBeInTheDocument();
    expect(
      screen.getByText(/failure of the evaluation run, not a result about the candidate/i),
    ).toBeInTheDocument();
    expect(screen.queryByText(/total score/i)).toBeNull();
  });

  it("offers a retry on failure and re-reads afterwards", async () => {
    const { fetchMock } = await renderReport({ statusEnvelope: failedFixture });
    await userEvent.click(screen.getByRole("button", { name: /run it again/i }));
    await waitFor(() =>
      expect(
        fetchMock.mock.calls.some(
          ([, init]) => (init as RequestInit | undefined)?.method === "POST",
        ),
      ).toBe(true),
    );
  });

  it("treats a missing evaluation as 'not requested yet', not as an error", async () => {
    await renderReport({ status: 404 });
    expect(screen.getByText(/no evaluation for this interview yet/i)).toBeInTheDocument();
    expect(screen.getByRole("button", { name: /run evaluation/i })).toBeInTheDocument();
  });

  it("surfaces an unauthorized session rather than an empty report", async () => {
    await renderReport({
      status: 403,
      detail: "That session does not belong to this interview.",
    });
    expect(screen.getByText(/couldn't load the evaluation/i)).toBeInTheDocument();
    expect(screen.getByText(/does not belong to this interview/i)).toBeInTheDocument();
  });

  it("surfaces a network failure the same way", async () => {
    vi.stubGlobal("fetch", vi.fn(async () => {
      throw new TypeError("network down");
    }));
    render(<EvaluationReport sessionId={SESSION} />);
    await waitFor(() =>
      expect(screen.getByText(/can't reach the server/i)).toBeInTheDocument(),
    );
  });

  it("refuses to render a result that contradicts itself", async () => {
    await renderReport({
      violations: ["total_score 51 is not the sum of the discussed skills (38)"],
    });
    expect(screen.getByText(/was not shown/i)).toBeInTheDocument();
    expect(screen.getByText(/is not the sum of the discussed skills/)).toBeInTheDocument();
    // And no scores leak through from a half-rendered result.
    expect(screen.queryByText(/overall rating/i)).toBeNull();
  });
});

