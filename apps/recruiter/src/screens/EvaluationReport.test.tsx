describe("depth reached and depth demonstrated", () => {
  async function panelFor(skill: string, reached: string, demonstrated: string) {
    await renderReport({
      result: result((r) => {
        const row = r.skills.find((s) => s.skill_name === skill)!;
        row.depth.depth_reached = reached as never;
        row.depth.depth_demonstrated = demonstrated as never;
      }),
    });
    return cardFor(skill);
  }

  const SUBJECT = "Reconciliation";

  it.each([
    ["direct", "direct", "Direct answer", "Direct answer"],
    ["direct", "deep_probed", "Direct answer", "Probed twice"],
    ["deep_probed", "direct", "Probed twice", "Direct answer"],
    ["deep_probed", "deep_probed", "Probed twice", "Probed twice"],
  ])(
    "shows %s / %s as two separate labelled values",
    async (reached, demonstrated, reachedLabel, demonstratedLabel) => {
      const card = await panelFor(SUBJECT, reached, demonstrated);
      const reachedBlock = within(card).getByText("Depth reached").closest("div")!;
      const shownBlock = within(card).getByText("Depth demonstrated").closest("div")!;
      expect(within(reachedBlock).getByText(reachedLabel)).toBeInTheDocument();
      expect(within(shownBlock).getByText(demonstratedLabel)).toBeInTheDocument();
      expect(within(card).getByText(/How far Tara investigated this skill/i)).toBeInTheDocument();
      expect(
        within(card).getByText(/How far the candidate's own evidence went/i),
      ).toBeInTheDocument();
    },
  );

  it("explains deeply probed but shallowly demonstrated without calling it low", async () => {
    const card = await panelFor(SUBJECT, "deep_probed", "direct");
    expect(
      within(card).getByText(/Tara investigated further than the evidence reached/i),
    ).toBeInTheDocument();
  });

  it("explains a directly answered but deeply demonstrated skill as saturation", async () => {
    const card = await panelFor(SUBJECT, "direct", "deep_probed");
    expect(
      within(card).getByText(/went further than the interview needed to probe/i),
    ).toBeInTheDocument();
  });

  it("keeps the fixture's own contrasting cases visible side by side", async () => {
    await renderReport({ result: result() });
    const over = cardFor("Idempotent design");
    const saturated = cardFor("Reconciliation");
    expect(within(over).getByText(/Tara investigated further/i)).toBeInTheDocument();
    expect(
      within(saturated).getByText(/went further than the interview needed/i),
    ).toBeInTheDocument();
  });
});

