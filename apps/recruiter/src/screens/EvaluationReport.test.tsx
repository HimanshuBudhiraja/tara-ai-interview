describe("the pilot review panel", () => {
  function stubWithReview() {
    const posted: Array<Record<string, unknown>> = [];
    const fetchMock = vi.fn(async (url: string, init?: RequestInit) => {
      const address = String(url);
      if (address.endsWith("/review") && init?.method === "POST") {
        const body = JSON.parse(String(init.body));
        posted.push(body);
        return {
          ok: true,
          status: 201,
          json: async () => ({
            ...body,
            evaluation_id: "ev_test",
            session_id: SESSION,
            ai_recommendation: "Needs further evaluation",
            ai_total_score: 33,
            ai_percentage: 66,
            ai_coverage_percentage: 50,
            pilot_run_id: "pilot_test",
            created_at: 0,
            updated_at: 0,
          }),
        } as unknown as Response;
      }
      if (address.endsWith("/review")) {
        return {
          ok: true,
          status: 200,
          json: async () => ({
            session_id: SESSION,
            evaluation_id: "ev_test",
            reviews: [],
            verdicts: ["agree", "disagree", "needs_review"],
            reasons: ["wrong_evidence", "wrong_skill"],
          }),
        } as unknown as Response;
      }
      return { ok: true, status: 200, json: async () => result() } as unknown as Response;
    });
    vi.stubGlobal("fetch", fetchMock);
    return { posted };
  }

  async function renderWithReview() {
    const api = stubWithReview();
    render(<EvaluationReport sessionId={SESSION} />);
    await waitFor(() => expect(screen.queryByText(/loading the evaluation/i)).toBeNull());
    return api;
  }

  it("says plainly that a review changes nothing about the assessment", async () => {
    await renderWithReview();
    const review = screen.getByRole("heading", { name: "Pilot review" }).closest("section")!;
    expect(within(review).getByText(/cannot change the score/i)).toBeInTheDocument();
  });

  it("will not record a verdict without a reviewer", async () => {
    await renderWithReview();
    const review = screen.getByRole("heading", { name: "Pilot review" }).closest("section")!;
    await userEvent.click(within(review).getByRole("button", { name: "Agree" }));
    expect(within(review).getByRole("button", { name: /record review/i })).toBeDisabled();
  });

  it("will not record a disagreement with no category", async () => {
    await renderWithReview();
    const review = screen.getByRole("heading", { name: "Pilot review" }).closest("section")!;
    await userEvent.type(within(review).getByLabelText(/reviewer name/i), "Asha");
    await userEvent.click(within(review).getByRole("button", { name: "Disagree" }));
    const record = within(review).getByRole("button", { name: /record review/i });
    expect(record).toBeDisabled();

    await userEvent.click(
      within(review).getByRole("button", { name: /score does not match/i }),
    );
    expect(record).toBeEnabled();
  });

  it("posts the verdict, the categories and the reviewer's own recommendation", async () => {
    const { posted } = await renderWithReview();
    const review = screen.getByRole("heading", { name: "Pilot review" }).closest("section")!;
    await userEvent.type(within(review).getByLabelText(/reviewer name/i), "Asha");
    await userEvent.click(within(review).getByRole("button", { name: "Disagree" }));
    await userEvent.click(
      within(review).getByRole("button", { name: /attributed to the wrong skill/i }),
    );
    await userEvent.selectOptions(
      within(review).getByLabelText(/what would you have recommended/i),
      "Not suitable for this role",
    );
    await userEvent.click(within(review).getByRole("button", { name: /record review/i }));

    await waitFor(() => expect(posted).toHaveLength(1));
    expect(posted[0]).toMatchObject({
      reviewer: "Asha",
      verdict: "disagree",
      reasons: ["wrong_skill"],
      recommendation: "Not suitable for this role",
    });
    // Nothing it sends could be mistaken for an edit to the assessment.
    expect(Object.keys(posted[0])).not.toContain("score");
    expect(Object.keys(posted[0])).not.toContain("criteria");
  });

  it("leaves every figure on the page exactly as it was", async () => {
    await renderWithReview();
    const fixture = resultFixture as unknown as AssessmentResult;
    // `innerText` is not implemented in jsdom; `textContent` is the equivalent
    // for a comparison that only has to notice a figure changing.
    const before = document.body.textContent ?? "";
    const review = screen.getByRole("heading", { name: "Pilot review" }).closest("section")!;
    await userEvent.type(within(review).getByLabelText(/reviewer name/i), "Asha");
    await userEvent.click(within(review).getByRole("button", { name: "Disagree" }));
    await userEvent.click(
      within(review).getByRole("button", { name: /recommendation is wrong/i }),
    );
    await userEvent.click(within(review).getByRole("button", { name: /record review/i }));
    await waitFor(() =>
      expect(within(review).getByText(/changes nothing about the assessment/i)).toBeInTheDocument(),
    );
    expect(screen.getByText(fixture.overall.recommendation)).toBeInTheDocument();
    const after = document.body.textContent ?? "";
    for (const figure of [
      String(fixture.overall.total_score),
      String(fixture.overall.percentage),
      fixture.overall.overall_rating,
      fixture.overall.recommendation,
      String(fixture.coverage.coverage_percentage),
    ]) {
      expect(after.includes(figure)).toBe(before.includes(figure));
    }
  });
});
